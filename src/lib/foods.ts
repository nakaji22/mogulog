export function getFoodById(id: string): Food | undefined {
  return FOODS.find((f) => f.id === id);
}

export function searchFoods(query: string): Food[] {
  const q = query.trim();
  if (!q) return FOODS;
  return FOODS.filter(
    (f) => f.name.includes(q) || f.category.includes(q) || f.aliases.some((a) => a.includes(q)),
  );
}

